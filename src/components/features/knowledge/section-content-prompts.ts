export function getSectionPrompts(
  isText: boolean,
  isImage: boolean
): string[] {
  if (isText) {
    return [
      'Будьте конкретны. Вместо «расскажи о космосе» напишите «расскажи о формировании чёрных дыр в понятной форме для старшеклассника».',
      'Задайте роль. Напишите: «Ты — опытный маркетолог. Составь стратегию продвижения...» — это значительно улучшает качество ответов.',
      'Укажите формат. Попросите ответ в виде списка, таблицы, JSON или пошаговой инструкции.',
      'Используйте примеры. Покажите модели пример желаемого результата, и она адаптирует ответ под ваш стиль.',
      'Разбивайте сложные задачи на подзадачи — модель лучше справляется с конкретными шагами.',
    ]
  }
  if (isImage) {
    return [
      'Описывайте сцену подробно: объекты, освещение, ракурс, стиль, цветовую палитру и настроение.',
      'Указывайте стиль: «в стиле акварели», «фотореалистичный», «concept art», «аниме», «low poly 3D».',
      'Добавляйте технические параметры: «8k resolution», «cinematic lighting», «depth of field», «golden hour».',
      'Используйте негативные описания: «без текста», «без watermark», «без искажений лица».',
      'Экспериментируйте с референсами: «в стиле Studio Ghibli», «в стиле Monet», «в стиле cyberpunk».',
    ]
  }
  return [
    'Опишите движение: «камера плавно движется слева направо», «зум на объект», «drone shot сверху».',
    'Укажите длительность и темп: «медленное движение», «динамичная смена сцен», «таймлапс».',
    'Опишите атмосферу: «кинематографичный», «документальный», «мечтательный», «напряжённый».',
    'Задайте освещение: «золотой час», «неоновые вывески», «студийный свет», «контровой свет».',
    'Используйте описание переходов: «fade in», «плавный переход от дня к ночи».',
  ]
}
