import type { AIModel } from '@/types/models'

export function getSectionAbout(
  model: AIModel,
  isText: boolean,
  isImage: boolean
): string[] {
  if (isText) {
    return [
      `${model.name} — мощная языковая модель нового поколения. Способна вести естественный диалог, отвечать на сложные вопросы, писать код, анализировать данные и помогать в творческих задачах.`,
      `Модель обучена на обширном массиве данных и способна понимать контекст, следовать инструкциям и генерировать структурированные ответы высокого качества.`,
      `Текущая версия: ${model.versions[0]?.label ?? model.name}. Доступно ${model.versions.length} вариантов модели с разным балансом скорости, качества и стоимости.`,
    ]
  }
  if (isImage) {
    return [
      `${model.name} — передовая модель генерации изображений. Создаёт фотореалистичные картинки, иллюстрации, концепт-арт и многое другое из текстового описания.`,
      `Поддерживает различные стили — от фотографии до абстрактного искусства, обеспечивая высокую детализацию и точное следование промпту.`,
      `Текущая версия: ${model.versions[0]?.label ?? model.name}. Доступно ${model.versions.length} вариантов с разным разрешением и скоростью генерации.`,
    ]
  }
  return [
    `${model.name} — модель генерации видео из текста. Создаёт реалистичные видеоролики с контролем камеры, освещения и движения.`,
    `Обеспечивает плавное движение, физически корректные тени и отражения, поддерживает различные стили и жанры.`,
    `Текущая версия: ${model.versions[0]?.label ?? model.name}. Доступно ${model.versions.length} вариантов с различной длительностью и качеством.`,
  ]
}
